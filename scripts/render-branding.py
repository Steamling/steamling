#!/usr/bin/env python3
"""Rebuild every Steamling image that shows the steamling from its two sources:
packages/shared/steamling-branding/steamling-figure.svg (the character) and
steamling-wordmark.svg (the "steamling" lettering). Run it after editing either one.

  scripts/render-branding.py           rewrite the outputs (and the social PNG if rsvg-convert is here)
  scripts/render-branding.py --check   exit 1 if any output is out of date (make check runs this)

Each output nests the sources as inline <svg> elements, so it stays one self-contained file that
GitHub and librsvg both render. The boot splash animates the figure itself (steamling.awk), and the
wallpaper draws the logo, so neither is written here."""
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BRAND = ROOT / "packages/shared/steamling-branding"
DOCS = ROOT / "docs/images"


def inner(path, x, y, w, h):
    """The source file as a nested <svg> placed at x,y w*h, without its XML prologue."""
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"<\?xml[^>]*\?>\s*", "", text)
    text = re.sub(r"<!--.*?-->\s*", "", text, count=1, flags=re.S)
    return re.sub(r"<svg\b[^>]*?(viewBox=\"[^\"]*\")[^>]*>",
                  f'<svg x="{x}" y="{y}" width="{w}" height="{h}" \\1>', text, count=1).strip()


def logo(tile):
    """The logo: the figure over the wordmark. tile=True puts it on the docs' black tile."""
    if tile:
        head = ('<!-- Steamling logo for the docs: the logo on a black tile, so the white wordmark\n'
                '     reads on light pages too. Generated by scripts/render-branding.py. -->\n'
                '<svg xmlns="http://www.w3.org/2000/svg" width="440" height="480" viewBox="20 5 440 480">\n'
                '  <rect x="20" y="5" width="440" height="480" rx="48" fill="#000"/>\n')
    else:
        head = ('<!-- Steamling logo: the steamling over the "steamling" wordmark, on a transparent\n'
                '     ground made for dark fields. Generated by scripts/render-branding.py from\n'
                '     steamling-figure.svg and steamling-wordmark.svg; edit those, not this. The\n'
                '     PKGBUILD renders it for the Plasma splash and the wallpaper. -->\n'
                '<svg xmlns="http://www.w3.org/2000/svg" width="380" height="420" viewBox="50 35 380 420">\n')
    return ('<?xml version="1.0" encoding="UTF-8"?>\n' + head
            + inner(BRAND / "steamling-figure.svg", 65, 40, 350, 328) + "\n"
            + inner(BRAND / "steamling-wordmark.svg", 105, 358, 270, 56) + "\n</svg>\n")


def social():
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<!-- GitHub social preview (1280x640): the steamling beside the wordmark. Generated by\n'
            '     scripts/render-branding.py, which also writes steamling-social.png. -->\n'
            '<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="640" viewBox="0 0 1280 640">\n'
            '  <defs><linearGradient id="field" x1="0" y1="0" x2="0" y2="1">'
            '<stop offset="0" stop-color="#25272E"/><stop offset="1" stop-color="#17181C"/>'
            '</linearGradient></defs>\n'
            '  <rect width="1280" height="640" fill="url(#field)"/>\n'
            + inner(BRAND / "steamling-figure.svg", 90, 70, 534, 500) + "\n"
            + inner(BRAND / "steamling-wordmark.svg", 640, 270, 560, 116) + "\n</svg>\n")


OUTPUTS = {
    BRAND / "steamling-logo.svg": lambda: logo(False),
    DOCS / "steamling-logo.svg": lambda: logo(True),
    DOCS / "steamling-social.svg": social,
}


def main():
    check = "--check" in sys.argv[1:]
    stale = [p for p, make in OUTPUTS.items()
             if not p.exists() or p.read_text(encoding="utf-8") != make()]
    if check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)} (run scripts/render-branding.py)")
        return 1 if stale else 0
    for p, make in OUTPUTS.items():
        p.write_text(make(), encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    if shutil.which("rsvg-convert"):
        subprocess.run(["rsvg-convert", "-w", "1280", "-h", "640", str(DOCS / "steamling-social.svg"),
                        "-o", str(DOCS / "steamling-social.png")], check=True)
        print("wrote docs/images/steamling-social.png")
    else:
        print("rsvg-convert not found: docs/images/steamling-social.png not refreshed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
